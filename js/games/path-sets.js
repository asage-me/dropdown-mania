/** How many sets there are, for copy that must never drift from the data. */
export const SET_COUNT = PATH_SETS.length;

/** The special picks that sit above the themed groups in the picker. */
export const RANDOM_PICK = "random";
export const JOURNEY_PICK = "journey";

/** Theme names in the order the picker should group them. */
export const PATH_THEMES = PATH_SETS.reduce((themes, set) => (
	themes.includes(set.theme) ? themes : [...themes, set.theme]
), []);

export function getSet(id) {
	return PATH_SETS.find((set) => set.id === id) || null;
}

/** A set id, never the same one twice in a row. */
export function randomSetId(avoidId) {
	const pool = PATH_SETS.filter((set) => set.id !== avoidId);
	const pick = (pool.length ? pool : PATH_SETS)[Math.floor(Math.random() * (pool.length || PATH_SETS.length))];
	return pick.id;
}
